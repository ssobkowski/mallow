/// A Luau bytecode format emitted by a compiler release.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
#[repr(u8)]
pub enum BytecodeVersion {
    /// Bytecode format 4.
    V4 = 4,
    /// Bytecode format 5.
    V5 = 5,
    /// Bytecode format 6.
    V6 = 6,
    /// Bytecode format 7.
    V7 = 7,
    /// Bytecode format 8.
    V8 = 8,
    /// Bytecode format 9.
    V9 = 9,
    /// Bytecode format 10.
    V10 = 10,
    /// Bytecode format 11.
    V11 = 11,
}

/// Error returned when a bytecode number is outside the supported range.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct InvalidBytecodeVersion {
    /// Number that could not be converted to a supported bytecode version.
    pub number: u8,
}

impl std::fmt::Display for InvalidBytecodeVersion {
    /// Formats the unsupported bytecode number.
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "unsupported Luau bytecode version {}",
            self.number
        )
    }
}

impl std::error::Error for InvalidBytecodeVersion {}

impl TryFrom<u8> for BytecodeVersion {
    type Error = InvalidBytecodeVersion;

    /// Converts a wire-format bytecode number into its typed representation.
    fn try_from(number: u8) -> Result<Self, Self::Error> {
        match number {
            4 => Ok(Self::V4),
            5 => Ok(Self::V5),
            6 => Ok(Self::V6),
            7 => Ok(Self::V7),
            8 => Ok(Self::V8),
            9 => Ok(Self::V9),
            10 => Ok(Self::V10),
            11 => Ok(Self::V11),
            number => Err(InvalidBytecodeVersion { number }),
        }
    }
}

impl From<BytecodeVersion> for u8 {
    /// Returns the numeric bytecode identifier encoded by this value.
    fn from(version: BytecodeVersion) -> Self {
        version as u8
    }
}

impl std::fmt::Display for BytecodeVersion {
    /// Writes the numeric bytecode identifier used in diagnostics.
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        u8::from(*self).fmt(formatter)
    }
}

/// A downloadable Luau archive for one target triple.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct PlatformAsset {
    /// Rust target triple used to select this archive.
    pub target: &'static str,
    /// File name used by the upstream release.
    pub archive_name: &'static str,
    /// HTTPS URL from which the archive is downloaded.
    pub url: &'static str,
    /// Lowercase SHA-256 digest of the complete archive.
    pub sha256: &'static str,
}

/// Metadata for one Luau release, including its bytecode format and platform archives.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Release {
    /// Upstream release number, such as `0.728`.
    pub version: &'static str,
    /// Bytecode format emitted by this compiler.
    pub bytecode: BytecodeVersion,
    /// Platform-specific archives belonging to this release.
    assets: &'static [PlatformAsset],
}

impl Release {
    /// Returns the archive matching the current operating system and CPU architecture.
    fn asset_for_current_platform(&self) -> Option<&'static PlatformAsset> {
        self.assets
            .iter()
            .find(|asset| asset.target == CURRENT_TARGET)
    }
}

