    /// Rejects forged executable hashes that are not backed by the trusted archive.
    #[test]
    fn forged_manifest_cannot_authenticate_tampered_executables() {
        let directory = tempfile::tempdir().unwrap();
        let cache = Cache::at(directory.path());
        let bytes = complete_archive();
        let hash = digest(&bytes);
        let installation = cache
            .install_archive(&fixture_release(), &bytes, &hash)
            .unwrap();
        let forged_contents = [
            b"forged-luau".as_slice(),
            b"forged-analyze",
            b"forged-compile",
            b"forged-ast",
        ];
        let forged_hashes = forged_contents.map(|contents| Some(digest(contents)));
        for (tool, contents) in Tool::all().into_iter().zip(forged_contents) {
            fs::write(installation.tool_path(tool), contents).unwrap();
        }
        fs::remove_file(installation.path().join(INSTALLATION_MANIFEST_NAME)).unwrap();
        write_installation_manifest(
            installation.path(),
            &InstallationManifest::new(&hash, forged_hashes),
        )
        .unwrap();

        assert!(!is_valid_installation(installation.path(), &hash));
        let repaired = cache
            .install_archive(&fixture_release(), &bytes, &hash)
            .unwrap();
        assert_eq!(fs::read(repaired.luau_path()).unwrap(), b"luau");
        assert!(is_valid_installation(repaired.path(), &hash));
    }

